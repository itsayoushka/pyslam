#!/usr/bin/env python3
"""GS-AgriField baseline benchmark — data preparation and run configurations.

    GSAF_DATA=<data root> python3 configs/gs_agrifield_benchmark/setup.py [ids...] [--no-convert]

Data layout under $GSAF_DATA: bags/<bag>/ (raw ROS 2 bags as downloaded from MARV) and
kitti/sequences/<bag>/ (KITTI-like conversions written by the dataset converter).

1. converts the raw ROS 2 bags that have no KITTI-like output yet (Docker image $CONVERTER_IMAGE,
   converter $GSAF_CONVERTER = scripts/mono_camera_kitti_converter.py of the dataset repository,
   images written unchanged);
2. builds data/kitti/pyslamdata/gsaf_<id>_<name>/ for every valid sequence:
     image_2/, calib.txt        symlinks to the converted sequence (container paths)
     times.txt                  image timestamps (header.stamp)
     groundtruth_simple.txt     /odom/sbg pose of imu_link per image (TUM + scale col., used by pySLAM itself)
     groundtruth_cam.tum        same poses moved to the camera optical frame: T_map_cam = T_map_imu * T_imu_cam
                                (used by our evaluation; removes the ~1.1 m camera lever arm)
     meta.json                  sequence metadata (crop, BBCH, speed, illumination, rig, extrinsics)
3. writes one pySLAM evaluation config per (sequence, method, repetition) in runs/.
Existing pySLAM datasets/configs are not touched; methods are used with pySLAM defaults.
"""
import json, os, shutil, subprocess, sys
import numpy as np
from scipy.spatial.transform import Rotation

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("PYSLAM_ROOT", os.path.dirname(os.path.dirname(HERE)))
DATA = os.path.join(ROOT, "data/kitti/pyslamdata")
GSAF_DATA = os.environ.get("GSAF_DATA", "")
CONVERTER = os.environ.get("GSAF_CONVERTER", "")
CONVERTER_IMAGE = os.environ.get("CONVERTER_IMAGE", "jazzy-vo-converter:latest")

# ---- benchmark design (identical for all methods: only the local feature pipeline changes) --------------
N_FEATURES = 8000
IMAGE_SCALE = 0.4               # 2880x1860 -> 1152x744, chosen by the resolution batch test (resolution_batch_test/DECISION.md)
LOOP_DETECTOR = "DBOW3_INDEPENDENT"  # same loop detection for every method (own ORB2 features + ORB-SLAM DBoW3 vocabulary)
REPETITIONS = 3                  # max attempts per (sequence, method): a failed run is retried with a new seed, stop at the first success
SEEDS = [12345, 23456, 34567]
METHODS = {                      # preset name -> pySLAM FeatureTrackerConfigs entry
    "orb2": "ORB2",                          # ORB-SLAM2 ORB extractor [Rublee 2011; Mur-Artal 2017]
    "sift_lightglue": "LIGHTGLUESIFT",        # SIFT + LightGlue [Lowe 2004; Lindenberger 2023] (GPU); plain SIFT failed seq 09 x3
    "akaze": "AKAZE",                        # [Alcantarilla 2013]
    "superpoint_lightglue": "LIGHTGLUE",     # SuperPoint + LightGlue [DeTone 2018; Lindenberger 2023] (GPU)
    # XFeat [Potje 2024] not evaluated: failed seq 09 with 3 matchers / 2 budgets (decision of 2026-10-16)
}
SETTINGS = {  # rig identified from fx of calib.txt (full resolution); settings generated at IMAGE_SCALE
    "rigA": (1943.82, os.path.join(HERE, "settings", "gsaf_rigA_s0p40.yaml")),
    "rigB": (1913.19, os.path.join(HERE, "settings", "gsaf_rigB_s0p40.yaml")),
}
SETTINGS_TEMPLATE = """# Generated by configs/gs_agrifield_benchmark/setup.py from {src}
# P matrix of /cam_nav1/hd/camera_info (rectified images, no distortion) scaled by {s} -> {w}x{h}
File.version: "1.0"

Camera.type: "PinHole"

Camera.fx: {fx:.9f}
Camera.fy: {fy:.9f}
Camera.cx: {cx:.9f}
Camera.cy: {cy:.9f}

Camera.k1: 0.0
Camera.k2: 0.0
Camera.p1: 0.0
Camera.p2: 0.0

Camera.fps: 10
Camera.RGB: 1

Camera.width: {w}
Camera.height: {h}

Viewer.KeyFrameSize: 0.1
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 1.0
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.15
Viewer.CameraLineWidth: 2.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -10.0
Viewer.ViewpointZ: -0.1
Viewer.ViewpointF: 2000.0

SAVE_TRAJECTORY:
  save_trajectory: True
"""
_SETTINGS_P = {}


def write_settings(rig, seq_dir):
    """One settings file per rig; every sequence of a rig must share the same calibration."""
    P = np.array(open(os.path.join(seq_dir, "calib.txt")).read().split()[1:], float).reshape(3, 4)
    if rig in _SETTINGS_P:
        assert np.allclose(_SETTINGS_P[rig], P, atol=1e-3), f"{seq_dir}: calibration differs within {rig}"
        return
    _SETTINGS_P[rig] = P
    os.makedirs(os.path.dirname(SETTINGS[rig][1]), exist_ok=True)
    s = IMAGE_SCALE
    open(SETTINGS[rig][1], "w").write(SETTINGS_TEMPLATE.format(
        src=f"calib.txt of {os.path.basename(seq_dir)}", s=s, w=round(2880 * s), h=round(1860 * s),
        fx=P[0, 0] * s, fy=P[1, 1] * s, cx=P[0, 2] * s, cy=P[1, 2] * s))
COLS = ["id", "name", "bag", "date", "crop", "bbch", "speed", "illumination", "valid", "note",
        "frames"]  # frames: optional "first-last" image range (inclusive) used instead of the whole sequence


def container_path(p):
    """run_docker.sh mounts $GSAF_DATA and the pySLAM root at the same paths inside the container."""
    return p


def read_seqs():
    if not GSAF_DATA:
        sys.exit("set GSAF_DATA to the data root (bags/ and kitti/sequences/)")
    rows = []
    for line in open(os.path.join(HERE, "sequences.tsv"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        vals = line.rstrip("\n").split("\t")
        s = dict(zip(COLS, vals + [""] * (len(COLS) - len(vals))))
        s["seq_dir"] = os.path.join(GSAF_DATA, "kitti", "sequences", s["bag"])
        s["bag"] = os.path.join(GSAF_DATA, "bags", s["bag"])
        s["extrinsics"] = "self"
        rows.append(s)
    return rows


def image_dir(seq_dir):
    """The dataset converter writes image_/; older conversions used image_2/."""
    return "image_" if os.path.isdir(os.path.join(seq_dir, "image_")) else "image_2"


def convert(seq_dir, bag):
    if not CONVERTER:
        sys.exit("set GSAF_CONVERTER to scripts/mono_camera_kitti_converter.py of the dataset repository")
    out_root = os.path.dirname(os.path.dirname(seq_dir))
    conv_dir = os.path.dirname(os.path.abspath(CONVERTER))
    cmd = ["docker", "run", "--rm", "-u", f"{os.getuid()}:{os.getgid()}",
           "-v", f"{bag}:/bag:ro", "-v", f"{out_root}:/out", "-v", f"{conv_dir}:/conv:ro",
           "--entrypoint", "bash", CONVERTER_IMAGE, "-c",
           f"source /opt/ros/jazzy/setup.bash && python3 /conv/{os.path.basename(CONVERTER)} "
           f"--bag /bag --out /out --seq {os.path.basename(seq_dir)} --no-export-unused-topics"]
    print("converting", bag, "->", seq_dir, flush=True)
    subprocess.run(cmd, check=True)


def read_T_imu_cam(path):
    lines = open(path).read().splitlines()
    i = next(k for k, l in enumerate(lines) if l.startswith("T_imu_link_camera"))
    j = next(k for k in range(i, len(lines)) if lines[k].strip().startswith("matrix_4x4"))
    T = np.array([[float(x) for x in lines[j + r].split()] for r in range(1, 5)])
    assert T.shape == (4, 4) and np.allclose(T[3], [0, 0, 0, 1]), path
    return T


def rig_of(seq_dir):
    fx = float(open(os.path.join(seq_dir, "calib.txt")).read().split()[1])
    rig = min(SETTINGS, key=lambda r: abs(SETTINGS[r][0] - fx))
    assert abs(SETTINGS[rig][0] - fx) < 1.0, f"unknown camera fx={fx} in {seq_dir}"
    return rig, fx


def write_tum(path, t, T):
    with open(path, "w") as f:
        for ti, Ti in zip(t, T):
            q = Rotation.from_matrix(Ti[:3, :3]).as_quat()
            x, y, z = Ti[:3, 3]
            f.write(f"{ti:.9f} {x:.9f} {y:.9f} {z:.9f} {q[0]:.12f} {q[1]:.12f} {q[2]:.12f} {q[3]:.12f}\n")


def prepare(s):
    seq_dir = s["seq_dir"]
    dst = os.path.join(DATA, f"gsaf_{s['id']}_{s['name']}")
    os.makedirs(dst, exist_ok=True)
    img = image_dir(seq_dir)
    for f in ("image_2", "calib.txt"):
        link = os.path.join(dst, f)
        if os.path.islink(link):
            os.remove(link)
        elif os.path.isdir(link):
            shutil.rmtree(link)
    os.symlink(container_path(os.path.join(seq_dir, "calib.txt")), os.path.join(dst, "calib.txt"))
    times = np.array([float(x) for x in open(os.path.join(seq_dir, "times.txt")) if x.strip()])
    P = [np.vstack([np.array(l.split(), float).reshape(3, 4), [0, 0, 0, 1]])
         for l in open(os.path.join(seq_dir, "poses.txt")) if l.strip()]
    n_img = len([f for f in os.listdir(os.path.join(seq_dir, img)) if f.endswith(".png")])
    assert len(times) == len(P) == n_img, (seq_dir, len(times), len(P), n_img)
    if s.get("frames"):
        # image range: image_2/ becomes a folder of per-image symlinks renumbered from 000000
        a, b = (int(x) for x in s["frames"].split("-"))
        assert 0 <= a <= b < n_img, (s["frames"], n_img)
        os.makedirs(os.path.join(dst, "image_2"))
        for k, i in enumerate(range(a, b + 1)):
            os.symlink(container_path(os.path.join(seq_dir, img, f"{i:06d}.png")),
                       os.path.join(dst, "image_2", f"{k:06d}.png"))
        times, P, n_img = times[a:b + 1], P[a:b + 1], b - a + 1
    else:
        os.symlink(container_path(os.path.join(seq_dir, img)), os.path.join(dst, "image_2"))
    assert np.all(np.diff(times) > 0), f"non-increasing timestamps in {seq_dir}"
    with open(os.path.join(dst, "times.txt"), "w") as f:
        f.writelines(f"{t:.9f}\n" for t in times)
    with open(os.path.join(dst, "groundtruth_simple.txt"), "w") as f:  # pySLAM format (imu_link poses)
        for t, T in zip(times, P):
            q = Rotation.from_matrix(T[:3, :3]).as_quat()
            f.write(f"{t:.9f} {T[0,3]:.9f} {T[1,3]:.9f} {T[2,3]:.9f} {q[0]:.12f} {q[1]:.12f} {q[2]:.12f} {q[3]:.12f} 1.0\n")
    ext = os.path.join(seq_dir, "nav_camera_to_imu_link.txt") if s["extrinsics"] == "self" else s["extrinsics"]
    T_imu_cam = read_T_imu_cam(ext)
    write_tum(os.path.join(dst, "groundtruth_cam.tum"), times, [T @ T_imu_cam for T in P])
    rig, fx = rig_of(seq_dir)
    write_settings(rig, seq_dir)
    pos = np.array([T[:3, 3] for T in P])
    meta = {k: s[k] for k in ("id", "name", "date", "crop", "bbch", "speed", "illumination", "note")}
    meta.update(frame_range=s.get("frames") or None, rig=rig, fx_full_res=fx, frames=n_img, duration_s=float(times[-1] - times[0]),
                path_length_m=float(np.linalg.norm(np.diff(pos, axis=0), axis=1).sum()),
                source_sequence=seq_dir, extrinsics_file=ext, T_imu_link_camera=T_imu_cam.tolist(),
                settings=SETTINGS[rig][1])
    json.dump(meta, open(os.path.join(dst, "meta.json"), "w"), indent=2)
    return dst, meta


def write_config(s, method, tracker, rig, rep):
    ds = f"gsaf_{s['id']}_{s['name']}"
    cfg = {
        "num_threads": 1,
        "seed": SEEDS[rep - 1],
        "dataset_base_path": DATA,
        "dataset_type": "FOLDER_DATASET",
        "number_of_runs_per_dataset": 1,
        "sensor_type": "mono",
        "plot_formats": ["png", "pdf"],
        "datasets": [{
            "name": ds,
            "settings_path": SETTINGS[rig][1],
            "images_glob_pattern": f"{ds}/image_2/*png",
            "fps": 10,
            "timestamps_path": f"{ds}/times.txt",
            "groundtruth_file": f"{ds}/groundtruth_simple.txt",
            "image_scale": IMAGE_SCALE,
        }],
        "presets": [{
            "name": method,
            "custom_parameters": {
                "config": {"GLOBAL_PARAMETERS": {"kUseLoopClosing": True, "kStoreKeyFrameImages": False}},
                "settings": {"FeatureTrackerConfig.name": tracker, "FeatureTrackerConfig.nFeatures": N_FEATURES,
                             "LoopDetectionConfig.name": LOOP_DETECTOR},
            },
        }],
        "output_path": f"gsaf_benchmark/{s['id']}_{s['name']}/{method}/rep{rep}",
        "saved_trajectory_format_type": "tum",
        "export_frame_logs": True,   # per-frame tracking state (frame_log.csv) for the tracked-frames metric
    }
    path = os.path.join(HERE, "runs", f"rep{rep}__{s['id']}_{s['name']}__{method}.json")
    json.dump(cfg, open(path, "w"), indent=2)


def main():
    do_convert = "--no-convert" not in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith("--")]
    os.makedirs(os.path.join(HERE, "runs"), exist_ok=True)
    for s in read_seqs():
        if only and s["id"] not in only:
            continue
        if s["valid"] != "1":
            print(f"{s['id']} {s['name']:30s} EXCLUDED: {s['note']}")
            continue
        if not os.path.isfile(os.path.join(s["seq_dir"], "poses.txt")):
            if not do_convert:
                print(f"{s['id']} {s['name']:30s} not converted yet (run without --no-convert)")
                continue
            convert(s["seq_dir"], s["bag"])
        dst, meta = prepare(s)
        for rep in range(1, REPETITIONS + 1):
            for m, tracker in METHODS.items():
                write_config(s, m, tracker, meta["rig"], rep)
        print(f"{s['id']} {s['name']:30s} frames={meta['frames']:5d} {meta['duration_s']:5.0f}s "
              f"{meta['path_length_m']:6.1f}m {meta['rig']} -> {dst}", flush=True)


if __name__ == "__main__":
    main()
